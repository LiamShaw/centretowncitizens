#!/usr/bin/env python3
"""Generate the Cloudflare Pages _redirects file from the built site.

Rather than predicting what URL Hugo will produce, this reads the built HTML
in public/ and maps each page's legacy Squarespace URL (recorded in a meta
tag at build time) to the path it was actually published at. That makes the
redirect map correct by construction, even when a slug contains characters
Hugo rewrites.

Usage:
    python tools/build_redirects.py [--public public] [--inventory data/inventory.csv]
                                    [--out public/_redirects]
"""

from __future__ import annotations

import argparse
import csv
import re
import sys
from pathlib import Path
from urllib.parse import quote

# Cloudflare Pages allows 2,000 static redirects in a _redirects file.
MAX_REDIRECTS = 2000

# The built HTML is minified, so attribute quotes may be absent.
LEGACY_RE = re.compile(
    r'<meta\s+name=["\']?legacy-url["\']?\s+content=["\']?([^"\'>\s]+)["\']?',
    re.IGNORECASE,
)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--public", default="public")
    parser.add_argument("--inventory", default="data-raw/inventory.csv")
    parser.add_argument("--out", default="public/_redirects")
    args = parser.parse_args()

    public = Path(args.public)
    if not public.exists():
        print(f"error: {public} not found. Run the Hugo build first.", file=sys.stderr)
        return 1

    # Map every published page's legacy URL to the path it was built at.
    legacy_to_path: dict[str, str] = {}
    for html_file in public.rglob("*.html"):
        rel = html_file.relative_to(public).as_posix()
        if rel.endswith("index.html"):
            path = "/" + rel[: -len("index.html")]
        else:
            path = "/" + rel[: -len(".html")]
        try:
            text = html_file.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        m = LEGACY_RE.search(text)
        if m and m.group(1):
            legacy_to_path.setdefault(m.group(1), path)

    # Pages that were deliberately dropped still need somewhere to point.
    dropped_targets: dict[str, str] = {}
    inventory = Path(args.inventory)
    if inventory.exists():
        with inventory.open(newline="", encoding="utf-8") as fh:
            for row in csv.DictReader(fh):
                status = (row.get("status") or "").lower()
                source = (row.get("source_url") or "").strip()
                if not source:
                    continue
                if status.startswith("dropped"):
                    dropped_targets[source] = row.get("new_url") or "/"

    # Collection index pages, which carry a legacy URL in their own front
    # matter but are not in the inventory.
    collection_aliases = {
        "/news": "/news/",
        "/advocacy": "/advocacy/",
        "/events": "/events/",
    }

    # The old advocacy page had a separate view per committee category. The
    # new site filters one page, so each category URL redirects with the
    # category as a query parameter.
    for category in (
        "All",
        "CCA",
        "SEPAW",
        "Planning",
        "Transportation",
        "Green",
        "HAWG",
    ):
        collection_aliases[f"/advocacy/category/{category}"] = f"/advocacy/?category={category}"

    redirects: dict[str, str] = {}
    for source, target in legacy_to_path.items():
        redirects[source] = target
    for source, target in collection_aliases.items():
        redirects.setdefault(source, target)
    for source, target in dropped_targets.items():
        redirects.setdefault(source, target or "/")

    # A redirect to itself is meaningless.
    redirects = {s: t for s, t in redirects.items() if s != t}

    if len(redirects) > MAX_REDIRECTS:
        print(
            f"error: {len(redirects)} redirects exceeds the Cloudflare Pages limit of {MAX_REDIRECTS}.",
            file=sys.stderr,
        )
        return 1

    target_file = Path(args.out)
    target_file.parent.mkdir(parents=True, exist_ok=True)
    with target_file.open("w", encoding="utf-8") as fh:
        fh.write("# Generated by tools/build_redirects.py. Do not edit by hand.\n")
        fh.write("# Every URL the old Squarespace site published.\n")
        for source in sorted(redirects):
            # Percent-encode both sides, so that a path containing a space
            # stays on one line and matches the raw request path.
            fh.write(f"{quote(source, safe='/')}  {quote(redirects[source], safe='/?=&')}  301\n")

    print(f"Wrote {len(redirects)} redirects to {target_file}")
    print(f"  from {len(legacy_to_path)} published pages")
    print(f"  plus {len(dropped_targets)} dropped pages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
